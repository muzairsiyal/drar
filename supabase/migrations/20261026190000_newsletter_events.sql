create table public.newsletter_subscribers (
  id uuid primary key default gen_random_uuid(),
  email text not null unique check (email = lower(trim(email)) and length(email) between 3 and 254),
  active boolean not null default true,
  unsubscribe_token uuid not null unique default gen_random_uuid(),
  subscribed_at timestamptz not null default now(),
  unsubscribed_at timestamptz
);

create table public.newsletter_events (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) between 2 and 160),
  message text not null check (length(trim(message)) between 2 and 10000),
  location text not null default '' check (length(location) <= 240),
  event_at timestamptz,
  status text not null default 'draft' check (status in ('draft', 'sending', 'sent', 'failed')),
  created_at timestamptz not null default now(),
  sent_at timestamptz
);

create table public.newsletter_deliveries (
  id uuid primary key default gen_random_uuid(),
  event_id bigint not null references public.newsletter_events(id) on delete cascade,
  subscriber_id uuid references public.newsletter_subscribers(id) on delete set null,
  recipient_email text not null,
  status text not null default 'pending' check (status in ('pending', 'sent', 'failed')),
  provider_id text,
  error text,
  attempted_at timestamptz,
  sent_at timestamptz,
  unique (event_id, recipient_email)
);

create index newsletter_deliveries_event_idx
  on public.newsletter_deliveries (event_id, status);

alter table public.newsletter_subscribers enable row level security;
alter table public.newsletter_events enable row level security;
alter table public.newsletter_deliveries enable row level security;

revoke all on public.newsletter_subscribers, public.newsletter_events, public.newsletter_deliveries
  from anon, authenticated;
grant select, update on public.newsletter_subscribers to authenticated;
grant select, insert, update, delete on public.newsletter_events to authenticated;
grant select on public.newsletter_deliveries to authenticated;
grant all on public.newsletter_subscribers, public.newsletter_events, public.newsletter_deliveries
  to service_role;
grant usage, select on sequence public.newsletter_events_id_seq to authenticated, service_role;

create policy "Admins view newsletter subscribers"
  on public.newsletter_subscribers for select to authenticated
  using ((select public.is_admin()));
create policy "Admins update newsletter subscribers"
  on public.newsletter_subscribers for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "Admins manage newsletter events"
  on public.newsletter_events for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "Admins view newsletter deliveries"
  on public.newsletter_deliveries for select to authenticated
  using ((select public.is_admin()));
