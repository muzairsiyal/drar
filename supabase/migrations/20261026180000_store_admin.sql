create table public.order_statuses (
  id bigint generated by default as identity primary key,
  label text not null unique check (length(trim(label)) between 2 and 80),
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.order_statuses (label, sort_order) values
  ('Order Placed / Received', 1),
  ('Ready for Delivery', 2),
  ('Shipped / Dispatched', 3),
  ('Out for Delivery', 4),
  ('Delivered', 5),
  ('Cancelled', 6);

alter table public.orders drop constraint if exists orders_status_check;

update public.orders
set status = case status
  when 'new' then 'Order Placed / Received'
  when 'packed' then 'Ready for Delivery'
  when 'shipped' then 'Shipped / Dispatched'
  when 'delivered' then 'Delivered'
  when 'cancelled' then 'Cancelled'
  else status
end;

alter table public.orders
  alter column status set default 'Order Placed / Received';

insert into public.order_statuses (label, sort_order, active)
select distinct status, 1000, false
from public.orders
where not exists (
  select 1 from public.order_statuses s where s.label = public.orders.status
);

create table public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  status text not null,
  changed_at timestamptz not null default now(),
  changed_by uuid references auth.users(id) on delete set null
);

insert into public.order_status_history (order_id, status, changed_at)
select id, status, created_at from public.orders;

create index order_status_history_order_idx
  on public.order_status_history (order_id, changed_at, id);

create or replace function public.validate_order_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    if not exists (
      select 1 from public.order_statuses
      where label = new.status and active
    ) then
      raise exception 'Choose an active order status';
    end if;
  end if;
  return new;
end;
$$;

create trigger orders_validate_status
before insert or update of status on public.orders
for each row execute function public.validate_order_status();

create or replace function public.record_order_status_history()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into public.order_status_history (order_id, status, changed_by)
    values (new.id, new.status, auth.uid());
  end if;
  return new;
end;
$$;

create trigger orders_record_status_history
after insert or update of status on public.orders
for each row execute function public.record_order_status_history();

