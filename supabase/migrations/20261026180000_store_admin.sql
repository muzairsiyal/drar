on public.order_statuses for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

create or replace function public.rename_order_status(p_status_id bigint, p_label text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_old_label text;
  v_new_label text := trim(p_label);
begin
  if not (select public.is_admin()) then
    raise exception 'Admin access required';
  end if;
  if length(v_new_label) not between 2 and 80 then
    raise exception 'Status must be between 2 and 80 characters';
  end if;

  select label into v_old_label
  from public.order_statuses
  where id = p_status_id and active
  for update;
  if not found then
    raise exception 'Active order status not found';
  end if;
  if exists (
    select 1 from public.order_statuses
    where label = v_new_label and id <> p_status_id
  ) then
    raise exception 'That order status already exists';
  end if;

  update public.order_statuses set label = v_new_label where id = p_status_id;
  update public.orders set status = v_new_label where status = v_old_label;
end;
$$;

revoke all on function public.rename_order_status(bigint, text) from public, anon;
grant execute on function public.rename_order_status(bigint, text) to authenticated;

create policy "Customers read status history for their orders"
on public.order_status_history for select to authenticated
using (
  exists (
    select 1 from public.orders
    where orders.id = order_status_history.order_id
      and (orders.user_id = (select auth.uid()) or (select public.is_admin()))
  )
);

