create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text not null default '',
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer not null default 0,
  active boolean not null default true
);

create table public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  category_id bigint references public.categories(id) on delete restrict,
  price_pkr integer not null check (price_pkr > 0),
  sale_price_pkr integer check (sale_price_pkr is null or (sale_price_pkr > 0 and sale_price_pkr < price_pkr)),
  stock integer not null default 0 check (stock >= 0),
  image_url text,
  badge text not null default '',
  tags text[] not null default '{}',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.store_settings (
  id boolean primary key default true check (id),
  shipping_fee_pkr integer not null default 250 check (shipping_fee_pkr >= 0),
  free_shipping_over_pkr integer not null default 5000 check (free_shipping_over_pkr >= 0),
  updated_at timestamptz not null default now()
);

insert into public.store_settings (id) values (true) on conflict (id) do nothing;

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique default ('DR-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10))),
  user_id uuid references public.profiles(id) on delete set null,
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  delivery_address text not null,
  delivery_city text not null,
  subtotal_pkr integer not null check (subtotal_pkr >= 0),
  shipping_pkr integer not null check (shipping_pkr >= 0),
  total_pkr integer not null check (total_pkr = subtotal_pkr + shipping_pkr),
  payment_method text not null check (payment_method in ('cod', 'online')),
  payment_status text not null check (payment_status in ('unpaid', 'pending', 'paid', 'failed', 'refunded')),
  status text not null default 'new' check (status in ('new', 'packed', 'shipped', 'delivered', 'cancelled')),
  guest_tracking_token_hash text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete restrict,
  product_name text not null,
  unit_price_pkr integer not null check (unit_price_pkr > 0),
  quantity integer not null check (quantity > 0),
  line_total_pkr integer generated always as (unit_price_pkr * quantity) stored
);

create table public.wishlist_items (
  user_id uuid not null references public.profiles(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);

create table public.reviews (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete restrict,
  user_id uuid not null references public.profiles(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  body text not null check (length(trim(body)) between 5 and 3000),
  status text not null default 'pending' check (status in ('pending', 'published', 'rejected')),
  created_at timestamptz not null default now()
);

create table public.support_tickets (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references public.profiles(id) on delete set null,
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null default '',
  order_reference text not null default '',
  subject text not null,
  message text not null,
  status text not null default 'open' check (status in ('open', 'in_progress', 'resolved', 'closed')),
  admin_reply text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

