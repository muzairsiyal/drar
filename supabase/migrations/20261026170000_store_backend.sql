create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, phone)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'phone', '')
  );
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.restore_cancelled_order_stock()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if old.status <> 'cancelled' and new.status = 'cancelled' then
    update public.products p
    set stock = p.stock + oi.quantity
    from public.order_items oi
    where oi.order_id = new.id and p.id = oi.product_id;
  elsif old.status = 'cancelled' and new.status <> 'cancelled' then
    if exists (
      select 1
      from public.order_items oi
      join public.products p on p.id = oi.product_id
      where oi.order_id = new.id and p.stock < oi.quantity
    ) then
      raise exception 'Insufficient stock to reopen this order';
    end if;
    update public.products p
    set stock = p.stock - oi.quantity
    from public.order_items oi
    where oi.order_id = new.id and p.id = oi.product_id;
  end if;
  return new;
end;
$$;

create trigger orders_restore_cancelled_stock
after update of status on public.orders
for each row execute function public.restore_cancelled_order_stock();

create or replace function public.create_cod_order(
  p_user_id uuid,
  p_customer_name text,
  p_customer_email text,
  p_customer_phone text,
  p_delivery_address text,
  p_delivery_city text,
  p_items jsonb,
  p_tracking_token_hash text
)
returns table (
  id uuid,
  order_number text,
  subtotal_pkr integer,
  shipping_pkr integer,
  total_pkr integer,
  status text
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_item record;
  v_product public.products%rowtype;
  v_order_id uuid;
  v_subtotal integer := 0;
  v_shipping integer;
  v_free_shipping_over integer;
  v_unit_price integer;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 30 then
    raise exception 'Invalid order items';
  end if;
  if length(trim(p_customer_name)) not between 1 and 120
     or length(trim(p_customer_email)) not between 3 and 254
     or length(trim(p_customer_phone)) not between 5 and 40
     or length(trim(p_delivery_address)) not between 5 and 500
     or length(trim(p_delivery_city)) not between 1 and 100
     or p_tracking_token_hash is null or p_tracking_token_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'Invalid customer details';
  end if;

  select shipping_fee_pkr, free_shipping_over_pkr
  into v_shipping, v_free_shipping_over
  from public.store_settings where id = true;
  if not found then
    raise exception 'Store settings are not configured';
  end if;

  insert into public.orders (
    user_id, customer_name, customer_email, customer_phone,
    delivery_address, delivery_city, subtotal_pkr, shipping_pkr,
    total_pkr, payment_method, payment_status, guest_tracking_token_hash
  ) values (
    p_user_id, trim(p_customer_name), lower(trim(p_customer_email)), trim(p_customer_phone),
    trim(p_delivery_address), trim(p_delivery_city), 0, 0, 0,
    'cod', 'unpaid', p_tracking_token_hash
  ) returning orders.id into v_order_id;

  for v_item in
    select (item ->> 'product_id')::bigint as product_id,
           sum((item ->> 'quantity')::integer)::integer as quantity
    from jsonb_array_elements(p_items) as entries(item)
    group by (item ->> 'product_id')::bigint
    order by (item ->> 'product_id')::bigint
  loop
    if v_item.quantity < 1 or v_item.quantity > 20 then
      raise exception 'Invalid product quantity';
    end if;

    select * into v_product
    from public.products
    where products.id = v_item.product_id and products.active
    for update;

    if not found or v_product.stock < v_item.quantity then
      raise exception 'A product is unavailable or out of stock';
    end if;

    v_unit_price := case
      when v_product.sale_price_pkr is not null then v_product.sale_price_pkr
      else v_product.price_pkr
    end;
    v_subtotal := v_subtotal + v_unit_price * v_item.quantity;

    insert into public.order_items (
      order_id, product_id, product_name, unit_price_pkr, quantity
    ) values (
      v_order_id, v_product.id, v_product.name, v_unit_price, v_item.quantity
    );

    update public.products
    set stock = stock - v_item.quantity
    where products.id = v_product.id;
  end loop;

  if v_subtotal < 1 then
    raise exception 'Invalid order total';
  end if;
  if v_subtotal >= v_free_shipping_over then
    v_shipping := 0;
  end if;

  update public.orders
  set subtotal_pkr = v_subtotal,
      shipping_pkr = v_shipping,
      total_pkr = v_subtotal + v_shipping
  where orders.id = v_order_id;

  return query
  select orders.id, orders.order_number, orders.subtotal_pkr,
         orders.shipping_pkr, orders.total_pkr, orders.status
  from public.orders where orders.id = v_order_id;
end;
$$;

